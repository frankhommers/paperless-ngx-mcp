import fs from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';
import YAML from 'yaml';
import patches from '../specs/patches.cjs';
const spec = patches.patchContract(YAML.parse(fs.readFileSync('specs/paperless-ngx.yaml', 'utf8')));
const selected = new Set(Object.values(JSON.parse(fs.readFileSync('specs/tools.json', 'utf8'))));
const paths = {}, routes = {};
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!selected.has(operation.operationId)) continue;
    (paths[path] ??= {})[method] = operation;
    routes[operation.operationId] = { method: method.toUpperCase(), path };
  }
}
if (Object.keys(routes).length !== selected.size) throw new Error('Tool references an unknown operation');
// Retain only schemas reachable from these operations; no unrelated admin API.
const schemas = {};
function visit(value) {
  if (!value || typeof value !== 'object') return;
  if (value.$ref?.startsWith('#/components/schemas/')) {
    const name = value.$ref.split('/').at(-1);
    if (!schemas[name]) { schemas[name] = spec.components.schemas[name]; visit(schemas[name]); }
  }
  for (const child of Object.values(value)) visit(child);
}
visit(paths);
const contract = { ...spec, paths, components: { ...spec.components, schemas } };
const ast = await openapiTS(contract, {
  defaultNonNullable: false,
  transform(schema) {
    if (schema.format === 'binary') return ts.factory.createTypeReferenceNode('Blob');
  },
});
const files = {
  'src/api/generated/paperless.ts': '// Generated by npm run contract:generate; do not edit.\n' + astToString(ast),
  'src/api/generated/routes.ts': '// Generated by npm run contract:generate; do not edit.\nexport const routes = ' + JSON.stringify(routes, null, 2) + ' as const;\n',
};
for (const [path, content] of Object.entries(files)) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(path) || fs.readFileSync(path, 'utf8') !== content) throw new Error(`${path} is stale; run npm run contract:generate`);
  } else fs.writeFileSync(path, content);
}
console.log(`Contract: ${selected.size} operations, ${Object.keys(schemas).length} schemas; ${process.argv.includes('--check') ? 'checked' : 'generated'}.`);
